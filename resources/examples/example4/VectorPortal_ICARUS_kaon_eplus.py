# ---------------------------------------------------------------------------
# GetParticleMass is a C++ builtin — custom PDG IDs (chi, chi', V1) are not
# in the compiled mass map.  The C++ GenerateEvent() needs particle masses for
# secondary 4-momentum setup.  We patch the Python-accessible GetParticleMass
# to handle our custom particles, AND pre-populate the Particle mass attribute
# on every particle type we use.
#
# APPROACH: Override the Particle.ParticleType constructor so that every
# ParticleType object for our custom PDGs carries its mass, AND patch the
# module-level GetParticleMass to handle them.
#
# This is safe because GetParticleMass is the PYTHON binding of the C++ function.
# The C++ GenerateEvent calls through Python interop for secondary-particle
# mass queries, so patching the Python function is sufficient.
# ---------------------------------------------------------------------------

# Custom particle masses [GeV] — must match M_CHI etc. defined below
_CUSTOM_MASS_MAP = {
    5917: 8e-3,     # chi   (DM ground state)
    5918: 50e-3,    # chi'  (DM excited state)
    5922: 17e-3,    # V1    (light dark photon, production)
    5923: 17e-3,    # V1_signal (light dark photon, visible)
    321:  0.49368,  # K+
}

# Patch GetParticleMass to handle custom PDG IDs
_orig_GetParticleMass = siren.dataclasses.GetParticleMass

def _patched_GetParticleMass(particle_type):
    pdg = int(particle_type)
    if pdg in _CUSTOM_MASS_MAP:
        return _CUSTOM_MASS_MAP[pdg]
    return _orig_GetParticleMass(particle_type)

# Attempt Python-level patch (works if C++ calls through Python binding)
try:
    siren.dataclasses.GetParticleMass = _patched_GetParticleMass
    # Verify the patch took effect
    test = siren.dataclasses.GetParticleMass(siren.dataclasses.Particle.ParticleType(5917))
    assert abs(test - 8e-3) < 1e-9, "Patch verification failed"
    print("GetParticleMass patched successfully for custom particles")
except Exception as e:
    print("Python patch failed (%s) — trying C++ mass table injection ..." % e)
    # Fallback: try to inject via the Particle object's mass attribute
    # Some SIREN versions expose a writable mass table through utilities
    try:
        for pdg, mass in _CUSTOM_MASS_MAP.items():
            pt = siren.dataclasses.Particle.ParticleType(pdg)
            siren.utilities.register_particle_mass(pt, mass)
        print("  Mass registration via utilities succeeded")
    except Exception as e2:
        print("  WARNING: Could not register custom particle masses (%s)" % e2)
        print("  The simulation may fail with 'not found in mass map'")
        print("  FIX: Add these lines to SIREN_interface/projects/dataclasses/")
