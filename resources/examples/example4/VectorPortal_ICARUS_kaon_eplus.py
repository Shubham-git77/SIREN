def make_fiducial_metric(fiducial, signal_pdgid=PDGID_V1_SIGNAL):
    from siren.math import Vector3D
    def metric(event, w):
        for datum in event.tree:
            r = datum.record
            if int(r.signature.primary_type) == signal_pdgid:
                vtx = Vector3D(*r.interaction_vertex[:3])
                if fiducial.IsInside(vtx):
                    return w
        return 0.0
    return metric

