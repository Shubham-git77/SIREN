# ---------------------------------------------------------------------------
# Vertex distributions
#
# IMPORTANT: We do NOT use SecondaryBoundedVertexDistribution for the chi
# upscatter. The chi originates from V1 decay along the kaon path, which
# starts at the BNB target (~600 m upstream of ICARUS). With VertexWeightingMode
# Fixed, the kaon vertex is in beamline coordinates — chi starts far outside
# the detector geometry, so SIREN cannot ray-trace from there into a bounded
# fiducial box ("Both points required to be finite").
#
# Instead we use SecondaryPhysicalVertexDistribution everywhere (physical
# propagation length from decay width) and apply the fiducial cut at the
# WEIGHTING stage via fid_metric (only counts events where V1_signal vertex
# is inside the ICARUS fiducial). This is physically equivalent: we generate
# the full phase space and the fiducial metric zeroes out off-target events.
#
# The upscatter cross-section falls off rapidly with distance from the target,
# so the effective fiducial acceptance is recovered in the weights.
# ---------------------------------------------------------------------------
# ---------------------------------------------------------------------------
# Secondary vertex distributions
#
# We use SecondaryPhysicalVertexDistribution for ALL secondaries including
# the chi upscatter. SecondaryBoundedVertexDistribution causes "Both points
# finite" for any chi that doesn't geometrically intersect the fiducial box
# (kaons going at large angles produce chi that miss the detector).
#
# Instead, fiducial selection is done entirely at the WEIGHT stage via
# fid_metric — events where V1_signal vertex is outside ICARUS get weight=0.
# This is physically equivalent: the upscatter cross section is negligible
# outside the LAr so essentially all signal comes from inside anyway.
#
# The chi upscatter free path is ~50 light-years (σ~10^-38 cm²) so most
# events get weight~0 from the cross section already. The effective signal
# comes from the rare chi that DO pass through the LAr and upscatter.
# ---------------------------------------------------------------------------
