def build_sX_cdf_table(kaon_decay, n_nodes=257):
    """
    Build inverse-CDF for (e+, nu_e) invariant mass s_X.
    dGamma/ds_X proportional to dGamma/dE_V1 (constant Jacobian).
    """
    engine  = kaon_decay._decay
    m_M, m_l, m_V1 = engine.m_M, engine.m_l, engine.m_phi
    s_min   = m_l**2
    s_max   = (m_M - m_V1)**2
    eps     = 1e-9 * (s_max - s_min)
    s_nodes = np.linspace(s_min + eps, s_max - eps, n_nodes)
    E_V1    = (m_M**2 + m_V1**2 - s_nodes) / (2.0 * m_M)
    dens    = np.clip(np.asarray(engine.differential_decay_rate(E_V1), dtype=float), 0.0, None)
    cdf     = np.concatenate([[0.0],
                               np.cumsum(0.5*(dens[1:]+dens[:-1])*np.diff(s_nodes))])
    if cdf[-1] <= 0.0:
        raise RuntimeError("s_X marginal is zero — check decay engine")
    return s_nodes.tolist(), cdf.tolist()

